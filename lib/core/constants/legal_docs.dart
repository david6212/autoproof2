/// One legal document — a title and an ordered list of sections.
class LegalDoc {
  const LegalDoc({
    required this.id,
    required this.title,
    required this.summary,
    required this.sections,
  });

  /// Route segment, e.g. `/legal/privacy`.
  final String id;
  final String title;

  /// One line shown on the index screen.
  final String summary;
  final List<LegalSection> sections;
}

/// A numbered heading and the paragraphs under it. A paragraph beginning with
/// `• ` is rendered as a bullet.
class LegalSection {
  const LegalSection(this.heading, this.paragraphs);

  final String heading;
  final List<String> paragraphs;
}
