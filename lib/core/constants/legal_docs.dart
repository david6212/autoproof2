/// The app's legal documents, as content rather than screens.
///
/// Two rules govern every line here:
///
/// 1. **Only describe what the code actually does.** The privacy policy lists
///    the fields that are really written to Firestore, the third parties that
///    really receive a request, and says plainly what is *not* collected. Same
///    discipline as the claims audit in BUSINESS_ROADMAP section 10 — if a
///    sentence cannot be traced to the source, it does not belong.
/// 2. **Never name an entity we do not have.** All identifying details come
///    from [LegalInfo]; nothing is hardcoded.
